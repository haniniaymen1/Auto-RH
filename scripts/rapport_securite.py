class TocDocTemplate(SimpleDocTemplate):
    first_content_page = None

    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            if level == 0 and TocDocTemplate.first_content_page is None:
                TocDocTemplate.first_content_page = self.page
            # Numéro AFFICHÉ (le contenu repart à 1 après le sommaire romain)
            fcp = TocDocTemplate.first_content_page
            affiche = self.page - fcp + 1 if fcp else self.page
            self.notify("TOCEntry", (level, text, affiche, key))


ROMAN = {1: "i", 2: "ii", 3: "iii", 4: "iv", 5: "v", 6: "vi", 7: "vii", 8: "viii"}


def _decor(canvas, doc):
    canvas.saveState()
    # En-tête : titre + filet accent
    canvas.setFont("FreeSerif", 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 0.55 * inch, DOC_TITLE)
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 0.62 * inch, PAGE_W - MARGIN, PAGE_H - 0.62 * inch)
    # Pied : auteur + numéro de page (numérotage : romain pour sommaire, arabe ensuite)
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 0.62 * inch, PAGE_W - MARGIN, 0.62 * inch)
    canvas.setFont("FreeSerif", 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 0.45 * inch, "Équipe sécurité Auto-RH")
    fcp = TocDocTemplate.first_content_page
    if fcp is None or doc.page < fcp:
        num = ROMAN.get(doc.page, str(doc.page))
    else:
        num = str(doc.page - fcp + 1)
    canvas.drawRightString(PAGE_W - MARGIN, 0.45 * inch, num)
    canvas.restoreState()


