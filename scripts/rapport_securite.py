def add_heading(text, style=h1, level=0):
    key = "h_" + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def h1_block(text, first_para):
    return [CondPageBreak(H1_THRESHOLD),
            KeepTogether([add_heading(text), Paragraph(first_para, body)])]


def stat_row(items):
    cells, widths = [], []
    n = len(items)
    w = (AVAIL_W * 0.96) / n
    for big, lab in items:
        inner = Table([[Paragraph("<b>%s</b>" % big, stat_big)],
                       [Paragraph(lab, stat_lab)]], colWidths=[w - 10])
        inner.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
            ("BOX", (0, 0), (-1, -1), 1, ACCENT),
            ("TOPPADDING", (0, 0), (-1, 0), 8),
            ("BOTTOMPADDING", (0, -1), (-1, -1), 8),
            ("TOPPADDING", (0, 1), (-1, 1), 2),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        cells.append(inner)
        widths.append(w)
    t = Table([cells], colWidths=widths, hAlign="CENTER")
    t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                           ("LEFTPADDING", (0, 0), (-1, -1), 5),
                           ("RIGHTPADDING", (0, 0), (-1, -1), 5)]))
    return t


def tableau(header, rows, ratios, caption=None, align_center_cols=None):
    align_center_cols = align_center_cols or []
    widths = [r * AVAIL_W * 0.98 for r in ratios]
    data = [[Paragraph("<b>%s</b>" % c, th) for c in header]]
    for r in rows:
        line = []
        for i, c in enumerate(r):
            line.append(Paragraph(str(c), td_c if i in align_center_cols else td_l))
        data.append(line)
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style = [("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
             ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
             ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
             ("LEFTPADDING", (0, 0), (-1, -1), 6),
             ("RIGHTPADDING", (0, 0), (-1, -1), 6),
             ("TOPPADDING", (0, 0), (-1, -1), 5),
             ("BOTTOMPADDING", (0, 0), (-1, -1), 5)]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      colors.white if i % 2 == 1 else TABLE_ROW_ODD))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 10), t]
    if caption:
        out += [Spacer(1, 4), Paragraph(caption, cap)]
    out.append(Spacer(1, 8))
    return out


